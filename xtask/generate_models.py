#!/usr/bin/env python3
"""Generate Rust DTO structs for `ghl-models` from GoHighLevel's OpenAPI specs.

Usage:
    python3 xtask/generate_models.py <highlevel-api-docs-checkout> <crates/ghl-models>

Emits one Rust module per API module (V2 in `src/v2/`, V3 in `src/v3/`), each
feature-gated so consumers compile only what they use, plus a `Cargo.toml`
feature list and `lib.rs`/`mod.rs` wiring.

Design choices (documented in the crate docs too):
  * Fields listed in the spec's `required` are non-`Option`; everything else is
    `Option<T>` with `skip_serializing_if` so partial updates serialize cleanly.
  * String enums become `String` with the allowed values in the doc comment
    rather than Rust enums — GoHighLevel adds values without notice, and a
    closed enum would turn that into a deserialization failure.
  * Inline (anonymous) objects and multi-branch compositions become
    `serde_json::Value`; a single-`$ref` `allOf` wrapper resolves to the ref.
  * Unknown response fields are ignored rather than rejected, so upstream
    additions never break existing code.
"""
import json
import keyword
import pathlib
import re
import sys

RUST_KEYWORDS = {
    "as", "break", "const", "continue", "crate", "dyn", "else", "enum", "extern",
    "false", "fn", "for", "if", "impl", "in", "let", "loop", "match", "mod",
    "move", "mut", "pub", "ref", "return", "self", "Self", "static", "struct",
    "super", "trait", "true", "type", "unsafe", "use", "where", "while", "async",
    "await", "abstract", "become", "box", "do", "final", "macro", "override",
    "priv", "try", "typeof", "unsized", "virtual", "yield", "union",
}

HEADER = """// @generated by xtask/generate_models.py — do not edit by hand.
// Source: https://github.com/GoHighLevel/highlevel-api-docs
// Doc comments are HighLevel's own field descriptions, reflowed verbatim, so
// they aren't held to rustdoc's markdown conventions.
#![allow(missing_docs, clippy::doc_lazy_continuation, clippy::doc_overindented_list_items)]

use serde::{Deserialize, Serialize};
"""


def pascal(name: str) -> str:
    """Schema name -> Rust type name."""
    name = re.sub(r"[^0-9a-zA-Z]+", " ", name).strip()
    parts = [p for p in name.split() if p]
    out = []
    for p in parts:
        # Preserve existing internal capitalisation (e.g. "DTO" -> "Dto")
        out.append(p[0].upper() + p[1:] if p else p)
    result = "".join(out)
    if not result:
        result = "Unnamed"
    if result[0].isdigit():
        result = "N" + result
    return result


def snake(name: str) -> str:
    """Property name -> Rust field name."""
    s = re.sub(r"[^0-9a-zA-Z]+", "_", name)
    s = re.sub(r"(?<=[a-z0-9])([A-Z])", r"_\1", s)
    s = re.sub(r"(?<=[A-Z])([A-Z][a-z])", r"_\1", s)
    s = s.lower().strip("_")
    s = re.sub(r"_+", "_", s)
    if not s:
        s = "field"
    if s[0].isdigit():
        s = "n" + s
    if s in RUST_KEYWORDS or keyword.iskeyword(s):
        s = s + "_"
    return s


def doc_lines(text, indent="    "):
    if not text:
        return []
    text = re.sub(r"\s+", " ", str(text)).strip()
    if not text:
        return []
    out, line = [], ""
    for word in text.split():
        if len(line) + len(word) + 1 > 88:
            out.append(f"{indent}/// {line}")
            line = word
        else:
            line = f"{line} {word}".strip()
    if line:
        out.append(f"{indent}/// {line}")
    return out


class Generator:
    def __init__(self, spec, known_types):
        self.spec = spec
        self.schemas = (spec.get("components") or {}).get("schemas") or {}
        # Schema names defined in THIS spec — refs to anything else degrade to Value.
        self.known = known_types

    def ref_type(self, ref):
        name = ref.split("/")[-1]
        if name in self.known:
            return pascal(name)
        return None

    def rust_type(self, prop, required):
        """(rust_type, extra_doc_lines)"""
        docs = []

        # allOf with a single $ref is a description wrapper — unwrap it.
        for key in ("allOf", "oneOf", "anyOf"):
            branches = prop.get(key)
            if branches:
                if key == "allOf" and len(branches) == 1 and "$ref" in branches[0]:
                    t = self.ref_type(branches[0]["$ref"])
                    inner = t or "serde_json::Value"
                    return self.wrap(inner, required), docs
                docs.append("Multiple possible shapes in the spec; raw JSON.")
                return self.wrap("serde_json::Value", required), docs

        if "$ref" in prop:
            t = self.ref_type(prop["$ref"])
            if t is None:
                docs.append("Shape defined in another spec file; raw JSON.")
                return self.wrap("serde_json::Value", required), docs
            return self.wrap(t, required), docs

        enum_vals = prop.get("enum")
        if enum_vals:
            shown = ", ".join(f"`{v}`" for v in enum_vals[:12] if v is not None)
            if shown:
                docs.append(f"Allowed values: {shown}.")
            return self.wrap("String", required), docs

        t = prop.get("type")
        if t == "array":
            items = prop.get("items") or {}
            inner, idocs = self.rust_type(items, required=True)
            docs.extend(idocs)
            # Vec is already "empty-able", so skip the Option for optional arrays
            # and use serde(default) instead — nicer to work with.
            return f"Vec<{inner}>", docs
        if t == "object" or (t is None and "properties" in prop):
            if prop.get("properties"):
                docs.append("Nested object; raw JSON (see the API docs for its fields).")
            return self.wrap("serde_json::Value", required), docs
        if t == "string":
            fmt = prop.get("format")
            if fmt in ("date-time", "date"):
                docs.append(f"Format: {fmt} (ISO-8601 string).")
            return self.wrap("String", required), docs
        if t == "boolean":
            return self.wrap("bool", required), docs
        if t == "integer":
            return self.wrap("i64", required), docs
        if t == "number":
            return self.wrap("f64", required), docs

        return self.wrap("serde_json::Value", required), docs

    @staticmethod
    def wrap(inner, required):
        return inner if required else f"Option<{inner}>"

    def emit_struct(self, name, schema):
        lines = []
        lines.extend(doc_lines(schema.get("description"), indent=""))
        if not schema.get("description"):
            lines.append(f"/// `{name}` from the GoHighLevel OpenAPI spec.")
        lines.append("#[derive(Debug, Clone, Default, Serialize, Deserialize)]")
        lines.append(f"pub struct {pascal(name)} {{")

        required = set(schema.get("required") or [])
        props = schema.get("properties") or {}
        if not props:
            lines.append("    /// The spec defines no fields for this schema.")
            lines.append("    #[serde(flatten)]")
            lines.append("    pub extra: serde_json::Map<String, serde_json::Value>,")
            lines.append("}")
            return "\n".join(lines)

        seen = set()
        for prop_name, prop in props.items():
            is_req = prop_name in required
            field = snake(prop_name)
            while field in seen:  # guard against snake_case collisions
                field += "_alt"
            seen.add(field)

            rtype, extra_docs = self.rust_type(prop, is_req)
            for dl in doc_lines(prop.get("description")):
                lines.append(dl)
            for extra in extra_docs:
                lines.extend(doc_lines(extra))
            if is_req:
                lines.append("    /// Required by the API.")

            attrs = []
            if field != prop_name:
                attrs.append(f'rename = "{prop_name}"')
            if rtype.startswith("Vec<"):
                attrs.append("default")
                attrs.append('skip_serializing_if = "Vec::is_empty"')
            elif not is_req:
                attrs.append("default")
                attrs.append('skip_serializing_if = "Option::is_none"')
            if attrs:
                lines.append(f"    #[serde({', '.join(attrs)})]")
            lines.append(f"    pub {field}: {rtype},")
        lines.append("}")
        return "\n".join(lines)

    def emit_enum_alias(self, name, schema):
        """Top-level string enums become documented type aliases (forward-compatible)."""
        lines = []
        lines.extend(doc_lines(schema.get("description"), indent=""))
        vals = ", ".join(f"`{v}`" for v in (schema.get("enum") or []) if v is not None)
        if vals:
            lines.extend(doc_lines(f"Allowed values: {vals}.", indent=""))
        lines.append(
            "/// Kept as `String` so new upstream values don't break deserialization."
        )
        lines.append(f"pub type {pascal(name)} = String;")
        return "\n".join(lines)

    def render(self):
        out = [HEADER]
        for name, schema in sorted(self.schemas.items()):
            if schema.get("enum") and schema.get("type") == "string":
                out.append(self.emit_enum_alias(name, schema))
            else:
                out.append(self.emit_struct(name, schema))
            out.append("")
        return "\n".join(out)


def module_key(stem):
    return stem.replace("-v3", "")


def feature_name(stem):
    return module_key(stem)


def main():
    docs_root = pathlib.Path(sys.argv[1])
    out_crate = pathlib.Path(sys.argv[2])

    sets = {
        "v2": sorted((docs_root / "apps").glob("*.json")),
        "v3": sorted((docs_root / "apps/v3").glob("*.json")),
    }

    features = {}   # feature -> set of (version, module)
    stats = {}
    for version, files in sets.items():
        out_dir = out_crate / "src" / version
        out_dir.mkdir(parents=True, exist_ok=True)
        mod_entries = []
        for f in files:
            spec = json.loads(f.read_text())
            schemas = (spec.get("components") or {}).get("schemas") or {}
            if not schemas:
                continue
            key = module_key(f.stem)
            rust_mod = snake(key)
            gen = Generator(spec, known_types=set(schemas))
            (out_dir / f"{rust_mod}.rs").write_text(gen.render())
            mod_entries.append((rust_mod, feature_name(key), len(schemas)))
            features.setdefault(feature_name(key), set()).add(version)
            stats[f"{version}/{key}"] = len(schemas)

        # version-level mod.rs
        lines = [
            "// @generated by xtask/generate_models.py — do not edit by hand.",
            f"//! Data models for GoHighLevel API {version.upper()}.",
            "",
        ]
        for rust_mod, feat, count in sorted(mod_entries):
            lines.append(f'/// `{rust_mod}` models ({count} schemas).')
            lines.append(f'#[cfg(feature = "{feat}")]')
            lines.append(f'#[cfg_attr(docsrs, doc(cfg(feature = "{feat}")))]')
            lines.append(f"pub mod {rust_mod};")
        (out_dir / "mod.rs").write_text("\n".join(lines) + "\n")

    # lib.rs
    lib = f'''// @generated by xtask/generate_models.py — do not edit by hand.
//! # ghl-models
//!
//! Rust data models (DTOs) for the [GoHighLevel](https://www.gohighlevel.com)
//! API, generated from HighLevel's official OpenAPI specifications.
//!
//! Both API versions are covered: [`v2`] (the current stable API, `Version:
//! 2021-07-28`) and [`v3`] (`Version: v3`). Every API module is behind a cargo
//! feature so you compile only the models you use — enabling everything means
//! thousands of structs.
//!
//! ```toml
//! [dependencies]
//! ghl-models = {{ version = "0.1", features = ["contacts", "invoices"] }}
//! ```
//!
//! ## How these types are generated
//!
//! * Fields the spec marks `required` are non-`Option`; the rest are
//!   `Option<T>` that skip serialization when `None`, so partial updates work.
//! * Arrays are `Vec<T>` with `#[serde(default)]` — an absent list reads as empty.
//! * String enums are `String` with the allowed values in the doc comment.
//!   GoHighLevel introduces new values without notice, and a closed Rust enum
//!   would turn that into a deserialization failure.
//! * Anonymous nested objects and multi-branch compositions are
//!   `serde_json::Value`.
//! * Unknown fields in responses are ignored, never rejected, so upstream
//!   additions can't break your build.
//!
//! Regenerate with `xtask/generate_models.py` after HighLevel updates its specs.
//!
//! *Not affiliated with HighLevel Inc.*

#![cfg_attr(docsrs, feature(doc_cfg))]

pub mod v2;
pub mod v3;
'''
    (out_crate / "src").mkdir(parents=True, exist_ok=True)
    (out_crate / "src/lib.rs").write_text(lib)

    total = sum(stats.values())
    print(f"generated {total} DTOs across {len(features)} feature-gated modules")
    print(f"features: {len(features)}")
    for feat in sorted(features):
        print(f"  {feat}: {sorted(features[feat])}")
    return features


if __name__ == "__main__":
    main()
